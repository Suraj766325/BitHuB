import { defineConfig, loadEnv } from 'vite';
import react from '@vitejs/plugin-react';

/**
 * The DSA site (public/dsa) is plain HTML and cannot import src/config.js, so this plugin hands it the same
 * VITE_API_BASE_URL as dsa/js/env.js: emitted into the build, and served by the dev server. A backend move
 * then only changes .env.production. An empty value means "same origin" (the dev proxy below).
 */
function dsaApiConfig(apiBase) {
  const source = `/* generated by vite.config.js from VITE_API_BASE_URL */\nwindow.DSA_API = ${JSON.stringify(apiBase)};\n`;
  return {
    name: 'dsa-api-config',
    configureServer(server) {
      server.middlewares.use('/dsa/js/env.js', (req, res) => {
        res.setHeader('Content-Type', 'text/javascript');
        res.end(source);
      });
    },
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: 'dsa/js/env.js', source });
    },
  };
}

/**
 * Vite Configuration — BitHub Landing Page
 *
 * Production optimizations:
 * - base: './' ensures all asset paths are relative (works in any subdirectory)
 * - CSS and JS are automatically minified in production builds
 * - Asset inlining for small files (< 4KB) reduces HTTP requests
 * - Source maps disabled in production for smaller bundle size
 */
export default defineConfig(({ mode }) => ({
  plugins: [react(), dsaApiConfig(loadEnv(mode, '.', '').VITE_API_BASE_URL || '')],

  /* Relative base path for flexible deployment */
  base: './',

  build: {
    /* Output to bit-jaipur/ directory at root */
    outDir: '../bit-jaipur',
    emptyOutDir: true,

    /* Inline assets smaller than 4KB */
    assetsInlineLimit: 4096,

    /* Disable source maps in production */
    sourcemap: false,

    /* Rollup options for optimized chunks */
    rollupOptions: {
      output: {
        /* Organize output by type */
        assetFileNames: 'assets/[name]-[hash][extname]',
        chunkFileNames: 'assets/[name]-[hash].js',
        entryFileNames: 'assets/[name]-[hash].js',
        /* Advanced Code Splitting */
        manualChunks(id) {
          if (id.includes('node_modules')) {
            if (id.includes('react')) return 'react-vendor';
            if (id.includes('katex')) return 'katex-vendor';
            if (id.includes('canvas-confetti')) return 'utils-vendor';
            return 'vendor';
          }
        }
      },
    },

    /* Minification (uses Vite default — oxc in v8+) */

    /* Target modern browsers */
    target: 'es2020',
  },

  server: {
    /* Dev server port */
    port: 3000,
    host: '0.0.0.0',
    open: true,
    allowedHosts: true,
    /* Proxy backend requests to bypass PNA popup and CORS */
    proxy: {
      '/api': {
        target: process.env.VITE_BACKEND_URL || 'http://localhost:3001',
        changeOrigin: true
      },
      '/study-material': {
        target: process.env.VITE_BACKEND_URL || 'http://localhost:3001',
        changeOrigin: true
      },
      '/dev-root': {
        target: process.env.VITE_BACKEND_URL || 'http://localhost:3001',
        changeOrigin: true
      }
    }
  },
}));
