/**
 * generate-env.js
 * Reads environment variables from .env.local (for local development) or
 * process.env (for Vercel deployments) and writes bit-mesra/env-config.js.
 *
 * bit-mesra/env-config.js is git-ignored so keys are never committed to Git.
 */
const fs = require('fs');
const path = require('path');

const envLocalPath = path.join(__dirname, '.env.local');
const parsedEnv = {};

if (fs.existsSync(envLocalPath)) {
  const content = fs.readFileSync(envLocalPath, 'utf8');
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eqIdx = line.indexOf('=');
    if (eqIdx === -1) continue;
    const key = line.slice(0, eqIdx).trim();
    const val = line.slice(eqIdx + 1).trim().replace(/^['"]|['"]$/g, '');
    parsedEnv[key] = val;
  }
}

const getVar = (key, fallback = '') =>
  process.env[key] !== undefined ? process.env[key] : (parsedEnv[key] ?? fallback);

const pausedRaw = String(getVar('APPS_SCRIPT_PAUSED', 'false')).toLowerCase();
const isPaused = pausedRaw === 'true' || pausedRaw === '1';

const config = {
  APPS_SCRIPT_FEEDBACK_URL: getVar('APPS_SCRIPT_FEEDBACK_URL', ''),
  APPS_SCRIPT_ANALYTICS_URL: getVar('APPS_SCRIPT_ANALYTICS_URL', ''),
  APPS_SCRIPT_PAUSED: isPaused,
};

const outPath = path.join(__dirname, 'bit-mesra', 'env-config.js');
const fileContents = `// Auto-generated by generate-env.js — DO NOT COMMIT\nwindow.__BITHUB_ENV__ = ${JSON.stringify(config, null, 2)};\n`;

fs.writeFileSync(outPath, fileContents, 'utf8');
console.log('Generated bit-mesra/env-config.js successfully.');
